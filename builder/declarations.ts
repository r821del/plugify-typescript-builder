
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

interface AbiType {
    type: string;
}

interface AbiParameter extends AbiType {
    name: string;
}

interface PublicMethod {
    name: string;
    funcName: string;
    paramTypes: AbiParameter[];
    retType: AbiType;
}

function toTypeScript(type: string): string {
    const types: Record<string, string> = {
        void: 'void',
        bool: 'boolean',

        char8: 'number',
        char16: 'number',

        int8: 'number',
        int16: 'number',
        int32: 'number',
        int64: 'bigint',

        uint8: 'number',
        uint16: 'number',
        uint32: 'number',
        uint64: 'bigint',

        float: 'number',
        double: 'number',

        string: 'string',

        vector2: 'Vector2',
        vector3: 'Vector3',
        vector4: 'Vector4',
        matrix4x4: 'Matrix4x4'
    };

    if (type.endsWith('[]')) {
        const element = toTypeScript(type.slice(0, -2));
        return `${element}[]`;
    }

    const result = types[type.toLowerCase()];

    if (!result) {
        throw new Error(
            `Unsupported ABI type for .d.ts: ${type}`
        );
    }

    return result;
}

function identifier(value: string): string {
    if (!/^[A-Za-z_$][\w$]*$/.test(value)) {
        throw new Error(`Invalid TypeScript identifier: ${value}`);
    }

    return value;
}

export async function generateDeclarations(
    root: string,
    pluginName: string,
    methods: PublicMethod[]
): Promise<void> {
    const outputDir = join(root, 'types', 'generated');
    await mkdir(outputDir, { recursive: true });

    const lines: string[] = [
        '// Auto-generated by Plugify Builder.',
        '// Do not edit manually.',
        '',
        `declare module ':${pluginName}' {`
    ];

    const needsMathTypes = methods.some(method =>
        [...method.paramTypes, method.retType].some(item =>
            /^(vector[234]|matrix4x4)(\[\])?$/i.test(item.type)
        )
    );

    if (needsMathTypes) {
        lines.splice(3, 0,
            `    import type { Vector2, Vector3, Vector4, Matrix4x4 } from 'plugify';`
        );
    }

    const usedNames = new Set<string>();

    for (const method of methods) {
        const name = identifier(method.name);

        if (usedNames.has(name)) {
            throw new Error(`Duplicate exported API: ${name}`);
        }
        usedNames.add(name);

        const params = method.paramTypes.map(param => {
            return `${identifier(param.name)}: ${toTypeScript(param.type)}`;
        });

        const returnType = toTypeScript(method.retType.type);

        lines.push(
            `    export function ${name}(${params.join(', ')}): ${returnType};`
        );
    }

    lines.push('}', '');

    const outputFile = join(outputDir, `${pluginName}.d.ts`);

    await writeFile(outputFile, lines.join('\n'), 'utf8');

    console.log(`  ↳ types/generated/${pluginName}.d.ts`);
}